            <article class="article-content">
                <p class="article-lead">
                    Com menos de uma semana de governo, o novo presidente da Colômbia, Abelardo de la Espriella, já se envolveu em uma crise diplomática ao reconhecer a soberania de Israel sobre as Colinas de Golã, o que gerou ampla condenação dos países árabes.
                </p>

                <p>
                    Na noite de segunda-feira (10), em meio à resposta ao terremoto de magnitude 7,4 que devastou o oeste da Colômbia, o Ministério das Relações Exteriores colombiano anunciou reconhecer a soberania e o direito de Israel sobre as Colinas de Golã, algo que chamou de “essencial” para a defesa nacional do território e dos cidadãos israelenses.
                </p>

                <h2>O que são as Colinas de Golã</h2>

                <p>
                    As Colinas de Golã são uma região montanhosa no sudoeste da Síria que Israel reivindica como parte de seu território. A área é ocupada por assentamentos israelenses desde a década de 1970, por ocasião da Guerra dos Seis Dias, e foi anexada por Israel em 1981 — ato não reconhecido pela comunidade internacional. Golã segue disputada desde então, e o governo Netanyahu aprovou planos para expandir os assentamentos desde a queda do regime Assad, em dezembro de 2024.
                </p>

                <h2>Reação dos países árabes</h2>

                <p>
                    Diversos países árabes manifestaram repúdio ao reconhecimento colombiano e reafirmaram a soberania da Síria nas Colinas de Golã. O governo sírio de Ahmed al-Sharaa condenou e rejeitou categoricamente a decisão colombiana.
                </p>

                <p>
                    A Liga Árabe, composta por 22 países do Oriente Médio e da África, rejeitou fortemente a decisão do governo Espriella, enfatizou a soberania síria sobre Golã e pediu que a Colômbia reconsidere sua posição. Além disso, nações como Arábia Saudita, Catar, Egito, Turquia, Iêmen, Jordânia, Líbia e Líbano também emitiram comunicados próprios.
                </p>

                <h2>Colômbia se junta aos EUA</h2>

                <p>
                    Com a decisão, a Colômbia se tornou apenas o segundo Estado-membro da ONU a adotar esse posicionamento e se juntou aos Estados Unidos, que reconhecem a soberania israelense de Golã desde 2019 — no primeiro mandato de Donald Trump.
                </p>

                <p>
                    Tanto a mídia colombiana quanto o ex-presidente colombiano Gustavo Petro afirmaram que o país “se isolou” do resto do mundo com a decisão do governo Espriella. Petro, que deixou o poder na semana passada, criticou a decisão e afirmou que o reconhecimento seria uma “cobrança” de Tel Aviv por uma suposta contribuição para a eleição de Espriella. Até o momento, não havia confirmação dessa alegação.
                </p>

