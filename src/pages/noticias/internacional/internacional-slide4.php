            <article class="article-content">
                <p class="article-lead">
                    As buscas por sobreviventes do terremoto de magnitude 7,4 que devastou a Colômbia entraram no 3º dia nesta quarta-feira (12). O governo de Abelardo de la Espriella declarou desastre nacional.
                </p>

                <p>
                    O número de mortos na Colômbia foi ajustado para baixo nesta quarta, de 254 para <strong>233</strong>. O novo valor decorre de uma atualização da prefeitura de Cali na noite de terça, que revisou seu balanço local de 95 para 74 mortos. Cerca de três mil pessoas estão desaparecidas no país, segundo o governo.
                </p>

                <h2>Janela crítica para salvar vidas</h2>

                <p>
                    Os socorristas correm contra o tempo para localizar e resgatar com vida vítimas do terremoto em diversas cidades do país. A “janela de ouro” para encontrar sobreviventes está acabando, segundo especialistas, que destacam as primeiras 72 horas após um terremoto como as mais importantes nos esforços de resgate.
                </p>

                <blockquote>
                    Os bombeiros de Cali afirmaram que esta quarta-feira é “um dia crucial para salvar vidas”.
                </blockquote>

                <p>
                    Uma mulher foi resgatada com vida na noite de terça-feira, cerca de 36 horas após o terremoto. O presidente Abelardo de la Espriella celebrou o resgate de Daniela Largo Sanchez e afirmou que as equipes de buscas trabalham “incansavelmente dia e noite” para encontrar pessoas presas sob escombros.
                </p>

                <h2>Regiões mais atingidas</h2>

                <p>
                    Os estados mais atingidos pelo tremor mais forte da década na Colômbia são Chocó, Valle del Cauca, Risaralda, Quindío e Caldas, onde se concentram os mortos, feridos e a destruição. O Exército colombiano participa dos trabalhos de resgate nas cidades mais afetadas, como Cali, Pereira e Manizales.
                </p>

                <h2>Desastre nacional e ajuda internacional</h2>

                <p>
                    O governo da Colômbia declarou nesta quarta-feira situação de desastre nacional válida por um período prorrogável de 12 meses, abrangendo os estados de Antioquia, Caldas, Cauca, Chocó, Quindío, Cundinamarca, Risaralda, Huila, Valle del Cauca, Tolima, Putumayo e Norte de Santander.
                </p>

                <p>
                    A chefe da União Europeia, Ursula von der Leyen, anunciou nesta quarta um pacote de ajuda de dois milhões de euros (cerca de R$ 11,9 milhões) para apoiar as operações de resgate na Colômbia.
                </p>

