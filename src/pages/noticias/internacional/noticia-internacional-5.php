            <h1 class="article-title">
                Como conflitos globais e eleições influenciam o dólar frente ao real
            </h1>

            <!-- Subtítulo -->
            <p class="article-subtitle">
                Guerras, disputas comerciais, juros nos Estados Unidos e o calendário eleitoral brasileiro tornam o câmbio cada vez mais sensível às expectativas dos investidores. Entenda por que eventos distantes afetam o bolso do brasileiro.
            </p>

