                <p class="article-lead">
                   Acabou na semifinal a trajetória de Italo Ferreira na etapa de Teahupoo, no Taiti, do Circuito Mundial de surfe de 2026. Apesar do revés para o havaiano Seth Moniz, por 15.76 a 13.83, nesta quinta-feira (13), o potiguar deixará a Polinésia Francesa na liderança do ranking da WSL após sete das 13 etapas programadas no calendário desta temporada.
                </p>

                <p>
                    Duas horas depois de eliminar o brasileiro, Moniz, que era apenas o 31º do ranking e agora é o 19º, levou a melhor na final contra o americano Griffin Colapinto (8º), com direito a duas notas na casa dos 9 pontos, e conquistou seu primeiro troféu no CT ao vencer por 18.17 a 14.67. No feminino, a campeã foi a canadense Erin Brooks, agora a número 11.
                </p>

                <p>
                    Mesmo lidando com dores incômodas na região lombar, na última segunda, ao passar pelo round 2, o campeão olímpico (Tóquio 2020) e mundial (2019) já havia assegurado sua volta à ponta. Ele chegou a ser o número 1 por duas etapas, mas perdeu o posto depois da etapa brasileira, em Saquarema (RJ), no mês passado.
                </p>

                <p>
                    - Foi bem legal esse campeonato. Tinham altas ondas, mas acabou que peguei muita onda (na semifinal). Estava difícil de ouvir as notas, e eu acabei pegando mais ondas do que o necessário. As melhores ondas vieram para o Seth, ele estava mais conectado. Ele fez uma ótima campanha, parabéns para ele. Eu vim com o objetivo de ficar pelo menos em terceiro e consegui isso - afirmou Italo.
                </p>

                <p>
                    - Eu estava limitado por causa da minha lesão, mas estou muito feliz pela minha performance - acrescentou o surfista de 32 anos.
                </p>

                <h2>
                    Tira-teima com Ewing nas quartas
                </h2>

                <p>
                    Era o terceiro confronto entre Italo e o australiano Ethan Ewing apenas nesta temporada, cada um tinha uma vitória. E, para não dar mole, o brasileiro foi o primeiro a pegar uma onda. Com quatro minutos de bateria, ele tirou um tubo não muito longo, mas com boa profundidade, e abriu com 5.33 pontos. O potiguar quase encaixa outra parede na sequência. Porém, ele entrou e saiu. Ethan demorou para se jogar na primeira onda. A espera não valeu tanto assim: nota 5.17. O mar deu uma acalmada.
                </p>

                <p>
                    Faltando 21 minutos, o primeiro campeão olímpico da história encontrou um canudo consistente. Ele correu dentro do trilho e finalizou com duas manobras de borda. Os juízes deram 7.17, deixando o brasileiro com 12.50. Ewing, naquela altura, tinha 5.87 e precisava de 7.33 para virar. Ele teve duas tentativas em alguns minutos. Na primeira: 6.77. E 3.67 na outra. Ethan ficou com 11.94 e não virou. Italo respondeu com estilo. Ele pegou o maior tubo da bateria, deu um rasgadão e recebeu 8.33, nota no critério excelente, para aumentar sua vantagem. Com 15.50, o Brabo não precisou fazer mais nada e, sem sustos, avançou à semifinal.
                </p>

                <h2>
                    Derrota para havaiano na semi
                </h2>

                <p>
                    Diante do havaiano Seth Moniz (26º), Italo começou a semi com ritmo acelerado. Ele foi o primeiro a pegar onda na semifinal. Ele dropou uma parede, mas acabou desistindo e somou 2.17. Seth ameaçou surfar uma de bom tamanho, mas abortou a ação. Na sequência, o brasileiro colocou sua primeira média considerável no placar ao pegar um tubo curto: 5.83. Sem desacelerar o ritmo, o brasileiro se jogou em mais um canudo. Foi pequeno e rápido. Assim, ele recebeu 4.17, passando a vencer por 10.00 a 5.50, passados apenas cinco minutos de bateria.
                </p>

                <p>   
                    Em alta rotação, Italo Ferreira encontrou mais um tubo e conseguiu a melhor nota, até então, na bateria: 6.67. O brasileiro vencia por 12.50 a 5.50, quando restavam 24 minutos. Na reta final, Moniz cresceu bastante. Ele foi buscar um 7.83 e um 7.93 para virar em cima do potiguar. Com apenas três minutos para reagir, Italo não encontrou um tubão para carimbar sua vaga na final. Assim, ele deu adeus com a terceira colocação em Teahupoo.
                </p>

