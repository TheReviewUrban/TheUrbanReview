                <p class="article-lead">
                    O norte-americano Tresean Gore venceu o brasileiro Vicente Luque por decisão unânime no UFC 330, neste sábado (15), na Filadélfia, nos Estados Unidos. Mas, para sair vitorioso do octógono, o lutador precisou deixar alguns dentes pelo caminho. "Mr. Vicious", como é conhecido, ficou "banguela" após uma joelhada de Luque e exibiu o novo visual durante a entrevista pós-luta.
                </p>

                <p>
                    Gore dominou boa parte do combate e já tinha a vitória encaminhada no terceiro round. Em desvantagem, Luque tentou uma última cartada no fim e acertou o joelho esquerdo em cheio no rosto do adversário, praticamente no estouro do cronômetro. O golpe atingiu a parte inferior da boca do norte-americano e fez alguns de seus dentes caírem.
                </p>

                <p>
                    A tentativa do brasileiro, porém, não foi suficiente para mudar o resultado. Gore levou a melhor nas papeletas dos três juízes: 30-27, 30-27 e 29-28. O norte-americano terminou a luta com a boca sangrando e, ainda no octógono após o anúncio do vencedor, o entrevistador Joe Rogan o questionou sobre o ferimento.
                </p>

                <p>
                    – Ele ferrou com alguns dos meus dentes de baixo com uma joelhada. Mas, cara, eu não dou a mínima, sabe? É o que é. Eu consigo consertar essa merda. Talvez eu esteja falando com um pouco de língua presa agora, mas vou para casa e vou colocar dois conjuntos [de dentes] para deixar consertado antes de uma viagem – disse ele, que deixou a arena e foi direto para o hospital.
                </p>

                <p>
                    Com a vitória, Gore chegou ao quarto triunfo no UFC e deixou de ter cartel negativo na organização. Ele emendou sua segunda vitória consecutiva, depois de derrotar o russo Azamat Bekoev em abril. Já Luque, de 34 anos, sofreu sua nona derrota no UFC. O brasileiro, que está no Ultimate há mais de uma década, agora tem cartel de 17 vitórias e nove derrotas.
                </p>

                <p>
                    Também no card preliminar do UFC 330, o estreante Lucas Fernando venceu Rafael "Bipolar" Tobias por nocaute técnico em duelo brasileiro pelo peso-meio-pesado. Em outra luta com brasileiro, o norte-americano Charles Johnson finalizou Eduardo "Chapolin" no terceiro round do peso-mosca.
                </p>

