            <h1 class="article-title">
                Centrão troca disputa pela Presidência por bilhões em cadeiras no Congresso
            </h1>
            <!-- Subtítulo -->
            <p class="article-subtitle">
                Sete partidos optam pela neutralidade na eleição presidencial de 2026 e priorizam a ampliação de bancadas para garantir poder e recursos no Legislativo.
            </p>
