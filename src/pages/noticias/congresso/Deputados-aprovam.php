            <article class="article-content">
                <p class="article-lead">
                    O presidente da Câmara dos Deputados, Eduardo Cunha, afirmou que as comissões permanentes da Casa começariam a funcionar na semana seguinte. A declaração foi dada durante entrevista à TV Câmara.
                </p>

                <p>
                    As comissões permanentes são órgãos técnicos da Câmara responsáveis por analisar propostas legislativas antes que elas sejam apreciadas pelo Plenário. Cada comissão acompanha temas específicos e pode discutir, votar e emitir pareceres sobre matérias relacionadas à sua área de atuação.
                </p>

                <h2>Retomada dos trabalhos</h2>

                <p>
                    Segundo Cunha, a retomada do funcionamento das comissões permitiria que os projetos em tramitação voltassem a ser analisados pelos colegiados da Câmara.
                </p>

                <p>
                    O funcionamento das comissões é uma etapa importante do processo legislativo, pois grande parte das propostas passa inicialmente por esses órgãos antes de chegar à votação no Plenário.
                </p>

                <h2>Atuação das comissões</h2>

                <p>
                    As comissões permanentes são formadas por deputados de diferentes partidos e representam uma das principais estruturas de análise das proposições legislativas. Nelas, os parlamentares podem debater os projetos, apresentar mudanças e acompanhar políticas públicas relacionadas aos temas de cada colegiado.
                </p>

                <p>
                    A previsão de início das atividades marcou a retomada da análise de matérias pelas comissões da Câmara, permitindo o avanço da tramitação de propostas que dependiam dos pareceres e das discussões nesses colegiados.
                </p>

