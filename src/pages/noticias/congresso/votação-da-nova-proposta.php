            <article class="article-content">
                <p class="article-lead">
                    Os integrantes do Conselho Nacional de Justiça (CNJ) aprovaram por unanimidade, nesta terça-feira (4/8), a proposta orçamentária do órgão para o exercício de 2027. Os dados apresentados pelo presidente do CNJ e do Supremo Tribunal Federal (STF), ministro Edson Fachin, que relatou a matéria, preveem um aumento de 7,9% na peça orçamentária de 2026, estimado em R$ 345,1 milhões, para R$ 372,4 milhões em 2027.
                </p>
                <p>
                    O Pedido de Providências 0006087-88.2026.2.00.0000, que definiu o Projeto de Lei Orçamentária Anual (PLOA) de 2027, foi analisado na 11ª Sessão Ordinária de 2026, realizada nesta terça-feira.
                </p>
                <h2>Destinação dos recursos</h2>
                <p>
                    Os recursos serão destinados ao pagamento de pessoal, encargos sociais, benefícios, aposentadorias e pensões, além de despesas relacionadas ao funcionamento do CNJ, à fiscalização administrativa e financeira do Poder Judiciário e à gestão de políticas judiciárias. O orçamento também inclui recursos arrecadados pelo Fundo de Modernização do Conselho, criado pela Resolução CNJ n. 627/2025.
                </p>
                <h2>Conformidade com regras fiscais</h2>
                <p>
                    De acordo com Fachin, a proposta foi elaborada conforme as regras da Lei Complementar n. 200/2023, que instituiu o Regime Fiscal Sustentável, e observou as diretrizes previstas no Projeto de Lei do Congresso Nacional n. 2/2026, além dos parâmetros encaminhados pela Secretaria de Orçamento Federal do Ministério do Planejamento e Orçamento.
                </p>
