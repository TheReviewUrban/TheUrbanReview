            <article class="article-content">
                <p class="article-lead">
                    A elaboração do orçamento do Distrito Federal para 2027 foi tema de audiência pública realizada na quarta-feira (3), na Comissão de Economia, Orçamento e Finanças (CEOF) da Câmara Legislativa do Distrito Federal (CLDF). O debate sobre o Projeto de Lei de Diretrizes Orçamentárias (PLDO) ocorreu em meio às discussões sobre os impactos da crise envolvendo o Banco de Brasília (BRB) e seus possíveis reflexos sobre as contas públicas do DF.
                </p>
                <p>
                    O projeto encaminhado pelo Governo do Distrito Federal (GDF) prevê um orçamento de R$ 74,97 bilhões para 2027. Desse total, R$ 45,45 bilhões correspondem à receita própria do Distrito Federal e R$ 29,52 bilhões são provenientes do Fundo Constitucional do Distrito Federal (FCDF). Os recursos do FCDF são destinados à segurança pública (R$ 15,46 bilhões), saúde (R$ 8,52 bilhões) e educação (R$ 5,53 bilhões).
                </p>
                <h2>Preocupações com concursos e serviços públicos</h2>
                <p>
                    Durante a audiência, representantes de sindicatos manifestaram preocupação com a possibilidade de que os efeitos fiscais relacionados ao caso BRB resultem em medidas de contenção de gastos, afetando concursos públicos, nomeações e a valorização dos servidores.
                </p>
                <p>
                    Diretor do Sindicato dos Bancários de Brasília, Daniel Oliveira argumentou que as dificuldades fiscais enfrentadas pelo Distrito Federal antecedem os desdobramentos recentes envolvendo o banco e defendeu que a instituição seja analisada também pelo papel estratégico que desempenha no desenvolvimento econômico local.
                </p>
                <p>
                    “O caso BRB não pode servir de cortina de fumaça para problemas fiscais que já existiam. A piora da Capag [capacidade de pagamento] do DF começou em 2023, muito antes da atual crise do banco”, declarou o diretor do Sindicato.
                </p>
                <p>
                    Na mesma linha, a diretora do Sindicato dos Bancários, Samanta Nascimento, defendeu que a preservação do BRB está diretamente relacionada à manutenção de serviços prestados à população do Distrito Federal. “Salvar o BRB não é salvar o banqueiro. Salvar o BRB é salvar a população do Distrito Federal, é salvar o pagamento dos benefícios sociais que hoje o banco paga. E é também salvar as trabalhadoras e trabalhadores do BRB”, afirmou.
                </p>
                <h2>Saúde e nomeações em alerta</h2>
                <p>
                    A deputada distrital Dayse Amarílio (PSB-DF) questionou a falta de informações detalhadas sobre os impactos do acordo envolvendo o BRB nas finanças do Distrito Federal e cobrou mais transparência do governo sobre o cenário fiscal previsto para 2027.
                </p>
                <p>
                    Segundo a parlamentar, a proposta da LDO não esclarece de que forma eventuais restrições orçamentárias poderão afetar áreas essenciais como saúde, educação e assistência social. Amarílio também demonstrou preocupação com a possibilidade de contingenciamento de recursos da saúde e com os efeitos do acordo sobre concursos públicos, nomeações e reestruturações de carreira.
                </p>
                <p>
                    “A população tem que saber o que nós estamos votando. Até para fiscalizar o que nós estamos votando”, observou. A deputada destacou ainda a situação da rede pública de saúde do DF: “Nós estamos vivendo uma situação de colapso total. Tem hospital que não tem o básico. Estamos falando de leitos bloqueados por falta de recursos humanos.”
                </p>
                <p>
                    Representando a Comissão dos Cirurgiões-Dentistas, Igor Rodrigues reforçou as preocupações com a falta de profissionais na rede pública. Segundo ele, o Distrito Federal possui uma das menores coberturas de saúde bucal do país, com cerca de 30% de cobertura, além de centenas de cargos vagos na carreira. Existem mais de 600 cargos vagos de cirurgião-dentista, enquanto milhares de pacientes aguardam atendimento especializado.
                </p>
                <h2>Defesa dos serviços públicos e próximos passos</h2>
                <p>
                    Dayse Amarílio também defendeu que o debate sobre a situação do banco não seja tratado como uma disputa entre a instituição financeira e os servidores públicos. Segundo ela, os trabalhadores da instituição não podem ser responsabilizados pela crise atual e é necessário que as discussões sobre o acordo ocorram com transparência e responsabilidade.
                </p>
                <p>
                    “Quem criou o problema do BRB não foi esta Casa, não foi a população do Distrito Federal e não foi o trabalhador do banco. O trabalhador do BRB também não tem culpa”, afirmou.
                </p>
                <p>
                    Uma reunião pública para tratar sobre o BRB que estava marcada para ocorrer na CLDF no dia 3 foi remarcada para o dia 25 de junho. A mudança ocorre após a Comissão de Economia, Orçamento e Finanças abrir mão da realização da reunião, para que a discussão seja concentrada em uma convocação já marcada pela Comissão de Constituição e Justiça (CCJ), com a presença do presidente do BRB, Nelson Antônio de Souza.
                </p>
                <p>
                    Segundo informações da CLDF, o parecer preliminar da LDO deveria ser analisado até 9 de junho. O prazo para apresentação de emendas à proposta terminava no dia 17 de junho, e a votação do parecer geral deveria ocorrer até 30 de junho na Comissão e no plenário da Câmara. Somente após a aprovação da LDO 2027 a Câmara Legislativa poderia iniciar o recesso parlamentar de julho.
                </p>
