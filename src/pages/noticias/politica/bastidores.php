            <article class="article-content">
                <p class="article-lead">
                    O Supremo Tribunal Federal (STF) retomou os trabalhos do colegiado em sessão presencial no plenário da Corte. Durante a reabertura, o presidente do tribunal, ministro Edson Fachin, fez a leitura de um comunicado reforçando o papel da instituição na democracia e o respeito ao contraditório.
                </p>

                <p>
                    Em seu discurso de abertura, Fachin afirmou que as críticas feitas ao STF fortalecem a democracia e não fragilizam a Corte, contanto que mantidas dentro dos parâmetros do diálogo republicano.
                </p>

                <h2>Críticas e solidez institucional</h2>

                <p>
                    De acordo com o presidente do Supremo, a Corte é constantemente provocada a deliberar sobre grandes e complexos temas sociais, o que gera questionamentos naturais por parte da sociedade civil e dos demais Poderes.
                </p>

                <p>
                    "É oportuno, também, reafirmar que a força institucional do STF não reside na ausência de crítica, mas na capacidade de conviver com ela sem perder a serenidade necessária ao exercício da função jurisdicional", declarou Fachin.
                </p>

                <h2>Manifestações dos ministros e da PGR</h2>

                <p>
                    A sessão contou também com manifestações do Procurador-Geral da República, Paulo Gonet, e de ministros do colegiado. Após a fala inicial de Fachin, o ministro Gilmar Mendes pediu a palavra para reforçar o papel pacificador da Constituição e a necessidade de preservação da independência entre os Poderes.
                </p>

                <h2>Pauta do semestre</h2>

                <p>
                    Neste semestre, o Supremo deve analisar ações de grande impacto social e econômico. Entre os primeiros itens da pauta estão processos que discutem a restrição de isenção tributária para pessoas com deficiência (PCD).
                </p>

                <p>
                    Além das pautas tributárias, o plenário deve julgar desdobramentos de investigações de ampla repercussão nacional, matérias relacionadas ao escândalo do INSS e controvérsias referentes à distribuição de emendas parlamentares.
                </p>

