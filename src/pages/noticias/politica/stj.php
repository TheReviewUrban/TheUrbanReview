            <article class="article-content">
                <p class="article-lead">
                    O Superior Tribunal de Justiça (STJ) deve decidir nesta semana se aplica uma punição ao ministro
                    Marco Buzzi em um processo disciplinar relacionado a uma denúncia de assédio. A análise do caso
                    pode definir o futuro do magistrado na Corte.
                </p>

                <p>
                    O processo será analisado pelos integrantes do próprio tribunal. A decisão deverá considerar as
                    acusações apresentadas durante a investigação e os argumentos apresentados pela defesa do ministro.
                </p>

                <h1>
                    O que está em discussão
                </h1>

                <p>
                    O caso envolve uma denúncia de assédio atribuída a Marco Buzzi. O procedimento disciplinar foi
                    instaurado para apurar os fatos e avaliar se houve conduta incompatível com os deveres do cargo.
                </p>

                <h2>
                    Decisão do STJ
                </h2>

                <p>
                    A expectativa é que o STJ avalie o processo nesta semana. Entre os pontos em discussão está a
                    possibilidade de aplicação de uma sanção ao ministro. Dependendo da decisão, o caso poderá ter
                    consequências para a permanência de Buzzi no tribunal.
                </p>

                <h2>
                    Possível demissão
                </h2>

                <p>
                    Uma das possibilidades mencionadas no processo é a demissão do ministro. Como se trata de um
                    integrante do STJ, a eventual punição segue regras específicas aplicáveis aos magistrados e
                    depende da conclusão do procedimento disciplinar.
                </p>

                <h2>
                    Próximos passos
                </h2>

                <p>
                    Após a análise pelos ministros, o tribunal deverá formalizar o resultado do julgamento. O
                    desfecho poderá encerrar o processo disciplinar ou abrir novas etapas, conforme a decisão tomada
                    e os procedimentos previstos para o caso.
                </p>

                <p>
                    O julgamento é acompanhado de perto por integrantes do Judiciário e deve ter repercussão no
                    cenário político e institucional brasileiro.
                </p>

