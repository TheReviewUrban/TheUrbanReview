            <article class="article-content">
                <p class="article-lead">
                    O presidente dos Estados Unidos, Donald Trump, afirmou que o Irã deve escolher entre fechar um "acordo" ou declarar "rendição total". A declaração foi feita através de suas redes sociais e sinaliza um endurecimento na retórica sobre os conflitos na região do Oriente Médio.
                </p>

                <p>
                    Trump classificou a liderança de Teerã como "inacreditavelmente dúbia", afirmando que representantes iranianos solicitam encontros de negociação em um momento e, em seguida, declaram publicamente que não há qualquer tratativa em andamento com o governo norte-americano.
                </p>

                <h2>Declarações no Truth Social</h2>

                <p>
                    "A liderança iraniana é inacreditavelmente dúbia! Eles pedem uma reunião — alguns diriam que 'imploram' —, as conversas começam, com outras já marcadas para o futuro imediato, e então dizem de forma aberta e orgulhosa que não estão tendo nenhuma discussão, que nada está sendo tratado e que estão lidando apenas com Omã", publicou o presidente americano na Truth Social.
                </p>

                <h2>Controle do Estreito de Ormuz</h2>

                <p>
                    Na mesma mensagem, Trump destacou a presença das forças navais norte-americanas na região estratégica e assegurou que o Estreito de Ormuz — por onde transita relevante parcela do fluxo mundial de petróleo — está "completamente" sob controle da Marinha dos EUA.
                </p>

                <p>
                    Segundo ele, a passagem comercial para o Irã ficará bloqueada até que os termos de um acordo formal ou de rendição total sejam estabelecidos entre as partes.
                </p>

                <h2>Impasse diplomático e segurança marítima</h2>

                <p>
                    A posição de Donald Trump contrasta com o tom adotado no final de semana anterior, quando havia acenado para a possibilidade de avanço em termos de um acordo de paz. Em resposta, o regime iraniano negou reuniões diretas com Washington, afirmando manter tratativas mediadas por Omã para viabilizar rotas de tráfego de navios comerciais.
                </p>

                <p>
                    Enquanto o cenário diplomático permanece sem definição, nações europeias e países árabes discutem a criação de uma coalizão internacional com o objetivo de assegurar a navegação comercial na região.
                </p>

