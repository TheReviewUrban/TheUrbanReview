            <article class="article-content">
                <p class="article-lead">
                    A Polícia Federal apreendeu três celulares com o empresário Daniel Vorcaro, do Banco Master, ao cumprir os mandados judiciais expedidos pelo ministro André Mendonça, do Supremo Tribunal Federal (STF), na última quarta-feira (4) e prender o banqueiro pela segunda vez.
                </p>

                <p>
                    Esses celulares serão colocados junto aos demais aparelhos apreendidos desde a primeira prisão dele, em novembro de 2025, e passarão por perícia. Os conteúdos ainda serão analisados e ainda não há clareza se os arquivos são mais relevantes do que os encontrados no celular que ele usava quando foi preso pela primeira vez.
                </p>

                <h2>Primeira prisão e soltura</h2>

                <p>
                    Vorcaro foi preso pela primeira vez em 17 de novembro de 2025, quando tentava embarcar no Aeroporto de Guarulhos (SP) para Dubai. Ele disse que estava indo tratar de negócios com investidores, mas a PF aponta que era um subterfúgio para fugir em um jatinho para Malta porque ele sabia da existência de uma ordem de prisão.
                </p>

                <p>
                    O empresário foi liberado 12 dias depois, com tornozeleira eletrônica.
                </p>

                <h2>Motivo da nova prisão</h2>

                <p>
                    O empresário foi preso novamente depois que a PF, ao analisar mensagens trocadas por ele em aplicativos de conversas, descobriu indícios de que o dono do Master ordenou a invasão aos sistemas de informática do Ministério Público Federal.
                </p>

                <p>
                    O objetivo era obter cópia de documentos sigilosos de investigações contra ele, além de pedir o monitoramento de adversários e até ações violentas contra um jornalista.
                </p>

                <h2>Posição da defesa</h2>

                <p>
                    Em nota divulgada neste sábado (7), a defesa de Vorcaro cobrou acesso a dados brutos do aparelho para realizar uma perícia independente. Para os advogados do banqueiro, o requerimento, apresentado em 16 de fevereiro, ganhou “especial relevância” após a divulgação de conversas dele. Entre elas, uma com o ministro Alexandre de Moraes, do STF.
                </p>

                <p>
                    “O objetivo é permitir a análise independente por assistente técnico da defesa, conforme previsto na legislação processual, garantindo que a prova digital seja examinada com transparência, integridade e respeito ao devido processo legal, inclusive para avaliar a licitude dos procedimentos utilizados na obtenção dessas provas”, destacou a defesa.
                </p>

                <p>
