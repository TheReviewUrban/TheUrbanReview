            <article class="article-content">
                <p class="article-lead">
                    O governo federal publicou em edição extra do Diário Oficial da União (DOU) na noite desta quinta-feira (30) o decreto que detalha a liberação de R$ 5,7 bilhões em gastos do Orçamento de 2026, anunciada na semana passada pela equipe econômica.
                </p>

                <p>
                    O texto atualiza a programação orçamentária e financeira da União após a revisão das estimativas de receitas e despesas feita no terceiro relatório bimestral de avaliação fiscal.
                </p>

                <h2>Ministérios mais beneficiados</h2>

                <p>
                    Para os ministérios, foram liberados <strong>R$ 4,5 bilhões</strong>. Entre os mais beneficiados estão:
                </p>

                <ul>
                    <li class="inicial-noticia">Ministério das Cidades: <strong>R$ 1,2 bilhão</strong></li>
                    <li class="inicial-noticia">Ministério dos Transportes: <strong>R$ 1,016 bilhão</strong></li>
                    <li class="inicial-noticia">Ministério da Fazenda: <strong>R$ 540 milhões</strong></li>
                    <li class="inicial-noticia">Ministério da Ciência, Tecnologia e Inovação: <strong>R$ 336 milhões</strong></li>
                    <li class="inicial-noticia">Ministério do Desenvolvimento Agrário e Agricultura Familiar: <strong>R$ 300 milhões</strong></li>
                    <li class="inicial-noticia">Ministério da Educação: <strong>R$ 280 milhões</strong></li>
                </ul>

                <p>
                    As <strong>emendas parlamentares</strong> também foram contempladas com liberação de <strong>R$ 1,2 bilhão</strong>.
                </p>

                <h2>Por que a liberação foi possível?</h2>

                <p>
                    A autorização foi concedida porque o governo reestimou as despesas previstas para este ano e concluiu que havia espaço dentro do limite existente no chamado arcabouço fiscal, a regra para as contas públicas aprovada em 2023.
                </p>

                <p>
                    Pelas regras, o crescimento dos gastos não pode superar 2,5% ao ano em termos reais (acima da inflação do ano anterior). O governo também não pode ampliar as despesas acima de 70% do crescimento projetado pela arrecadação.
                </p>

                <p>
                    A medida havia sido anunciada no último dia 24 pelos ministérios da Fazenda e do Planejamento, juntamente com o relatório bimestral de receitas e despesas. Na ocasião, a equipe econômica informou que a revisão para baixo de algumas despesas obrigatórias abriu margem para ampliar os gastos discricionários — aqueles sobre os quais o governo tem maior poder de decisão.
                </p>

                <h2>Ainda há bloqueios</h2>

                <p>
                    Apesar da liberação de recursos, <strong>R$ 17,9 bilhões permanecem bloqueados</strong> no Orçamento deste ano. Os anexos do decreto mostram que esse montante continua sujeito a medidas de contenção distribuídas entre ministérios e emendas parlamentares.
                </p>

                <p>
                    Em maio, o governo havia informado uma contenção total de R$ 23,7 bilhões. Com a atualização das projeções fiscais, parte desses recursos pôde ser liberada, reduzindo o valor bloqueado.
                </p>

                <h2>Gastos livres</h2>

                <p>
                    A liberação de despesas ocorrerá nos chamados gastos livres dos ministérios, ou seja, aqueles que não são obrigatórios. Nessa categoria estão despesas administrativas, investimentos, manutenção de universidades federais, funcionamento de agências reguladoras, emissão de passaportes, bolsas da Capes e do CNPq, fiscalização ambiental e combate ao trabalho escravo, entre outras ações.
                </p>

                <p>
                    Já os gastos obrigatórios, que não podem ser alvo de bloqueio de recursos, envolvem, por exemplo, despesas com benefícios previdenciários, pensões, salário dos servidores públicos, abono e seguro-desemprego, entre outros.
                </p>

                <h2>Revisão das despesas</h2>

                <p>
                    A equipe econômica também reduziu projeções de despesas primárias para 2026. Entre os principais recuos estão:
                </p>

                <ul>
                    <li class="inicial-noticia">Pessoal e encargos sociais: <strong>R$ 4,2 bilhões</strong></li>
                    <li class="inicial-noticia">Benefícios previdenciários: <strong>R$ 3,2 bilhões</strong></li>
                    <li class="inicial-noticia">Benefício de Prestação Continuada (BPC): <strong>R$ 3,2 bilhões</strong></li>
                </ul>

                <p>
                    Segundo o ministro do Planejamento, Bruno Moretti, a redução nas estimativas relacionadas aos benefícios previdenciários está ligada ao ritmo de concessão desses benefícios.
                </p>

                <p>
                    Por outro lado, o governo aumentou as projeções de gastos com:
                </p>

                <ul>
                    <li class="inicial-noticia">Abono salarial e seguro-desemprego: <strong>R$ 1,6 bilhão</strong></li>
                    <li class="inicial-noticia">Saúde: <strong>R$ 3,4 bilhões</strong></li>
                </ul>

                <h2>Meta fiscal</h2>

                <p>
                    Além de cumprir os limites de crescimento das despesas previstos no arcabouço fiscal, o governo também precisa atingir a meta fiscal definida pela Lei de Diretrizes Orçamentárias (LDO).
                </p>

                <p>
                    Para 2026, a meta é registrar superávit de 0,25% do Produto Interno Bruto (PIB), o equivalente a cerca de R$ 34,3 bilhões. Pela legislação, há uma faixa de tolerância de 0,25 ponto percentual para mais ou para menos.
                </p>

                <p>
                    Com a revisão das projeções de receitas e despesas anunciada na semana passada, o governo passou a estimar déficit primário de R$ 52 bilhões em 2026, ante uma previsão anterior de R$ 60,3 bilhões. Os anexos do decreto publicado nesta quinta-feira mantêm a projeção de déficit de cerca de R$ 52 bilhões para este ano.
                </p>

                <p class="article-author">
                    Por <strong>Mariana Assis</strong> e Redação — Brasília
                </p>

