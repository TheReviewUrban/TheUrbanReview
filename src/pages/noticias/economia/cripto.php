            <article class="article-content">
                <p class="article-lead">
                    O Banco Central (BC) determinou a possibilidade de retenção de determinadas transferências de criptoativos por até <strong>24 horas</strong> para análise em caso de suspeita de fraude.
                </p>

                <p>
                    A medida considera o uso crescente de criptoativos, inclusive stablecoins, em operações fraudulentas que podem rapidamente ser direcionadas ao exterior ou para carteiras autocustodiadas, dificultando a recuperação dos recursos.
                </p>

                <h2>Quando a retenção será aplicada</h2>

                <p>
                    De acordo com a resolução, a retenção deverá ser aplicada a operações destinadas a prestadores de serviços de ativos virtuais no exterior ou a carteiras autocustodiadas quando o valor superar o equivalente a <strong>10 mil dólares</strong>.
                </p>

                <p>
                    Mesmo abaixo desse limite, a instituição deverá interromper temporariamente uma operação quando seus mecanismos de gerenciamento de riscos identificarem a necessidade de investigação adicional. A nova sistemática passa a valer em <strong>1º de janeiro de 2027</strong>.
                </p>

                <h2>Responsabilidade das empresas</h2>

                <p>
                    Para o advogado Fabiano Jantalia, sócio-fundador do Jantalia Advogados e especialista em Direito Bancário e Compliance Financeiro, a principal mudança está na responsabilidade atribuída às empresas que intermedeiam essas operações.
                </p>

                <blockquote>
                    “O Banco Central está deixando claro que o combate a fraudes não pode ser apenas uma atividade posterior à ocorrência do problema. A instituição precisa ter estrutura de compliance capaz de identificar comportamentos de risco e interromper uma operação quando necessário.”
                </blockquote>

                <p>
                    Na avaliação do especialista, a regra também reforça a importância de investimentos em tecnologia e governança pelas empresas do setor. O desafio jurídico e operacional é grande: as prestadoras terão de demonstrar a efetividade de políticas de gerenciamento de risco, mecanismos de monitoramento e procedimentos internos coerentes com o perfil das operações e dos clientes.
                </p>

                <p>
                    Ainda que a implementação tenha desafios, ele considera a medida extremamente necessária.
                </p>

                <blockquote>
                    “Quanto mais sofisticado fica o mercado de ativos virtuais, maior é a necessidade de demonstrar segurança, rastreabilidade e capacidade de resposta. A empresa que investir em governança e prevenção não estará apenas cumprindo uma exigência do regulador, mas também construindo confiança para operar em um mercado cada vez mais institucionalizado.”
                </blockquote>

