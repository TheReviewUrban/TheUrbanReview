                    <p>
                        "Esses incidentes destacam a importância de implementar as atividades de monitoramento exigidas
                        dos desenvolvedores."
                    </p>

                    <h2>
                        Relembre os casos
                    </h2>

                    <p>
                        Na quinta-feira (30), a Anthropic informou que alguns modelos da família Claude invadiram os
                        sistemas de três empresas durante testes de cibersegurança.
                    </p>

                    <p>
                        Segundo a empresa, um erro de configuração permitiu que os modelos tivessem acesso à internet.
                        As invasões começaram em abril e foram identificadas durante uma revisão de mais de 141 mil
                        sessões de teste. A Anthropic afirmou que notificou as empresas afetadas após descobrir os
                        incidentes.
                    </p>

                    <p>A revelação ocorreu poucos dias depois de a OpenAI informar que dois de seus modelos de
                        inteligência artificial encontraram uma forma de invadir um sistema e realizar um ataque
                        considerado "sem precedentes" durante testes de segurança.</p>

                    <p>
                        Os dois casos reacenderam o debate sobre os riscos de agentes de IA capazes de executar tarefas
                        de forma autônoma.
                    </p>

                    <h2>
                        O que muda com a Lei de IA
                    </h2>

                    <p>
                        A Lei de IA da União Europeia entra em vigor em 2 de agosto e estabelece obrigações para
                        desenvolvedores de modelos de inteligência artificial considerados de uso geral e com risco
                        sistêmico.
                    </p>

                    <p>
                        A Lei de IA da União Europeia entra em vigor em 2 de agosto e estabelece obrigações para
                        desenvolvedores de modelos de inteligência artificial considerados de uso geral e com risco
                        sistêmico.
                    </p>

                    <p>Entre as exigências estão medidas para monitorar e reduzir riscos relacionados a ataques
                        cibernéticos, manipulação maliciosa, ameaças a direitos fundamentais e situações em que sistemas
                        de IA possam agir fora do controle humano.
                    </p>

                    <p>
                        As regras também preveem transparência em determinadas aplicações, como informar usuários quando
                        estiverem interagindo com inteligência artificial ou quando um conteúdo tiver sido gerado ou
                        alterado por IA.
                    </p>

                    <p>
                        As multas por descumprimento podem variar de 7,5 milhões de euros (cerca de R$ 48 milhões) ou
                        1,5% do faturamento global da empresa até 35 milhões de euros (cerca de R$ 224 milhões) ou 7% da
                        receita mundial, dependendo da gravidade da infração.
                    </p>

