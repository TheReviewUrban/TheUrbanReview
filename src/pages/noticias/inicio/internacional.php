                <p class="article-lead">
                    Segundo autoridades da União Europeia, as duas companhias comunicaram os incidentes antes que eles
                    se tornassem públicos. A Comissão afirmou que acompanha o caso e avalia se será necessário adotar
                    medidas formais.
                </p>

                <p>
                    Anteriormente, a pasta informou que cerca de 50 mil pessoas cruzaram a fronteira desde a manhã de
                    quinta-feira (30). Juan Jesús Vivas, chefe do governo local de Ceuta, afirmou que até 60 mil pessoas
                    haviam feito a travessia nos últimos dias.
                </p>

                <p>
                    Os episódios ocorrem poucos dias antes da entrada em vigor da Lei de IA da União Europeia, prevista
                    para 2 de agosto. A legislação é considerada a primeira do mundo a estabelecer regras abrangentes
                    para o desenvolvimento e o uso da inteligência artificial.
                </p>

                <h2>
                    O que disse a Comissão Europeia
                </h2>

                <hp>
                    Segundo um funcionário da Comissão Europeia, OpenAI e Anthropic informaram os incidentes diretamente
                    às autoridades europeias.
                    </p>

                    <p>
                        "Fomos informados pelos dois provedores sobre os incidentes antes de eles se tornarem públicos.
                        Estamos em contato com eles e receberemos mais informações. Também avaliaremos se será
                        necessário dar um encaminhamento mais formal a essas questões", afirmou.
                    </p>

                    <p>
                        Outro representante da Comissão disse que os episódios reforçam a importância das novas regras
                        para inteligência artificial.
                    </p>

